"""Shared helpers of check.py and index.py: repo root, bundle discovery, frontmatter and generated indexes."""
import os
import re
import subprocess

SKIP = {"vendor", "node_modules", ".git", ".claude", "source", "tmp", "dist"}
MARKER = "<!-- generated by index.py -->"
RESERVED = ("index.md", "log.md")
FRONTMATTER = re.compile(r"---\n(.*?\n)?---\n", re.S)


def repo_root():
    here = os.path.dirname(os.path.abspath(__file__))
    candidate = os.path.abspath(os.path.join(here, "..", "..", "..", ".."))
    if os.path.isdir(os.path.join(candidate, ".agents", "skills")):
        return candidate
    out = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True)
    if out.returncode != 0:
        raise SystemExit("no repo root: run inside a git repository")
    return out.stdout.strip()


def bundles(root, args):
    if args:
        missing = [a for a in args if not os.path.isdir(a)]
        if missing:
            raise SystemExit(f"not a directory: {', '.join(missing)}")
        return [os.path.abspath(a) for a in args]
    found = []
    for dirpath, dirs, _ in os.walk(root):
        if os.path.basename(dirpath) == "knowledge":
            found.append(dirpath)
            dirs[:] = []
            continue
        dirs[:] = sorted(d for d in dirs if d not in SKIP)
    return found


def enclosing(path):
    """The bundle root a folder sits inside, or None when no folder above it is named knowledge."""
    parent = os.path.dirname(os.path.abspath(path))
    while parent != os.path.dirname(parent):
        if os.path.basename(parent) == "knowledge":
            return parent
        parent = os.path.dirname(parent)
    return None


def walk(bundle):
    """Yields each directory of a bundle with its sorted sub-directories and .md files."""
    for dirpath, dirs, files in os.walk(bundle):
        dirs[:] = sorted(d for d in dirs if not d.startswith("."))
        yield dirpath, list(dirs), sorted(f for f in files if f.endswith(".md"))


def split(text):
    """Returns (frontmatter block or "", body, line count of the block)."""
    m = FRONTMATTER.match(text)
    if not m:
        return "", text, 0
    return m.group(0), text[m.end():], m.group(0).count("\n")


def unquote(value):
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def frontmatter(text):
    """Parses flat YAML: scalars, inline lists and block lists. Returns (fields, key lines) or None."""
    block, _, _ = split(text)
    if not block:
        return None
    fields, lines, key = {}, {}, None
    for number, line in enumerate(block.splitlines()[1:-1], start=2):
        stripped = line.strip()
        if key and stripped.startswith("- "):
            fields[key].append(unquote(stripped[2:]))
            continue
        if line.startswith((" ", "#")) or ":" not in line:
            continue
        key, value = line.split(":", 1)
        key, value = key.strip(), value.split(" #", 1)[0].strip()
        lines[key] = number
        if value.startswith("[") and value.endswith("]"):
            fields[key] = [unquote(v) for v in value[1:-1].split(",") if v.strip()]
        elif value == "":
            fields[key] = []
        else:
            fields[key] = unquote(value)
            key = None
    return fields, lines


def generated(text):
    _, body, _ = split(text)
    return body.lstrip("\n").startswith(MARKER + "\n") or body.strip() == MARKER


def title(name):
    words = name.replace("-", " ").replace("_", " ")
    return words[:1].upper() + words[1:]


def render(bundle, dirpath, dirs, files, current):
    """The generated index.md of a directory; the root keeps its frontmatter, or gets okf_version "0.2"."""
    head = ""
    if dirpath == bundle:
        block, _, _ = split(current or "")
        head = (block or '---\nokf_version: "0.2"\n---\n') + "\n"
    lines = [MARKER, "", f"# {title(os.path.basename(dirpath))}", ""]
    for name in files:
        if name in RESERVED:
            continue
        with open(os.path.join(dirpath, name), encoding="utf-8") as f:
            fields = (frontmatter(f.read()) or ({}, {}))[0]
        label = fields.get("title") or name[:-3]
        description = fields.get("description")
        lines.append(f"- [{label}]({name})" + (f" - {description}" if description else ""))
    for d in dirs:
        lines.append(f"- [{d}/]({d}/index.md)")
    return head + "\n".join(lines).rstrip("\n") + "\n"


def display(path):
    rel = os.path.relpath(path)
    return path if rel.startswith("..") else rel
