"""Writes the generated index.md of every directory of OKF bundles.

Usage: python3 -I index.py [bundle ...]

With no argument it serves every directory named knowledge in the repo. It writes index.md where the file is missing
or starts with the marker line <!-- generated by index.py -->; a hand-written index.md stays as it is. A folder inside
a bundle is refused with exit code 1, and the message names the bundle root.
"""
import importlib.util
import os
import sys

# -I leaves the script's folder off sys.path, so the shared module loads by its path.
sys.dont_write_bytecode = True
_here = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location("okf", os.path.join(_here, "okf.py"))
okf = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(okf)


def serve(bundle):
    written = 0
    for dirpath, dirs, files in okf.walk(bundle):
        path = os.path.join(dirpath, "index.md")
        current = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                current = f.read()
            if not okf.generated(current):
                continue
        text = okf.render(bundle, dirpath, dirs, files, current)
        if text != current:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            print(f"wrote {okf.display(path)}")
            written += 1
    return written


def main(args):
    root = okf.repo_root()
    for arg in args:
        outer = okf.enclosing(arg)
        if outer:
            raise SystemExit(f"{arg} sits inside a bundle: its root is {okf.display(outer)}; "
                             "run index.py on the root, or with no argument")
    total = sum(serve(bundle) for bundle in okf.bundles(root, args))
    print(f"{total} index.md written")


if __name__ == "__main__":
    main(sys.argv[1:])
