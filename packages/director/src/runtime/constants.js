// Director Lingo constants
// See: docs/drmx2004_scripting_ref.txt Chapter 9: Constants

/**
 * Constant; represents the Backspace key. This key is labeled Backspace in Windows
 * and Delete on the Macintosh.
 */
export const BACKSPACE = String.fromCharCode(51);

/**
 * Character constant; represents the empty string, "", a string with no characters.
 */
export const EMPTY = "";

/**
 * Character constant; represents Enter (Windows) or Return (Macintosh) for a
 * carriage return.
 */
export const ENTER = String.fromCharCode(3);

/**
 * Constant; applies to an expression that is logically FALSE, such as 2 > 3.
 * When treated as a number value, FALSE has the numerical value of 0.
 */
export const FALSE = false;

/**
 * Constant; returns the value of pi (π).
 */
export const PI = Math.PI;

/**
 * Constant; represents the quotation mark character.
 */
export const QUOTE = '"';

/**
 * Constant; represents a carriage return.
 */
export const RETURN = "\r";

/**
 * Constant; read-only, value that represents the space character.
 */
export const SPACE = " ";

/**
 * Constant; represents the Tab key.
 */
export const TAB = "\t";

/**
 * Constant; represents the value of a logically true expression.
 */
export const TRUE = true;

/**
 * Constant; indicates the value VOID.
 */
export const VOID = null;
