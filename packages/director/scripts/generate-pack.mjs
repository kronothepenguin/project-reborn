#!/usr/bin/env node
// 007 pack generator — emits a per-cast / per-movie `index.js` from the
// decompiled CSVs (Members.csv / Casts.csv), conforming to the C8 definition
// contract that the 008 ingester + builders consume.
//
// Usage:
//   node scripts/generate-pack.mjs cast <castDir>            -> writes <castDir>/index.js
//   node scripts/generate-pack.mjs movie <movieDir>          -> writes <movieDir>/index.js
//
// Cast input: <castDir>/Members.csv (Number,Type,Name,Registration Point,Filename)
//   - script rows: payload.content = the sibling `.js` file (translated script)
//     if present, else the `.ls` file verbatim.
//   - bitmap rows: payload.data = filename contents as base64 data URI.
//   - other media types: payload.{data|text} as appropriate.
// Movie input: <movieDir>/Casts.csv (Number,Name,Filename) + the sibling cast
//   dirs named <name> (or <Filename>); empty slots (Filename empty) become
//   empty casts; totalCastSlots = max Number.

import { readFileSync, readdirSync, existsSync, writeFileSync } from "node:fs";
import path from "node:path";

function parseCsv(text) {
  const rows = [];
  const lines = text.split(/\r?\n/).filter((l) => l.trim().length > 0);
  for (const line of lines.slice(1)) {
    const cells = [];
    let cur = "";
    let inQ = false;
    for (let i = 0; i < line.length; i++) {
      const c = line[i];
      if (c === '"') {
        if (inQ && line[i + 1] === '"') { cur += '"'; i++; }
        else inQ = !inQ;
      } else if (c === "," && !inQ) {
        cells.push(cur); cur = "";
      } else cur += c;
    }
    cells.push(cur);
    rows.push(cells);
  }
  return rows;
}

function mediaTypeFrom(type) {
  const t = String(type).toLowerCase();
  if (t === "script") return "script";
  if (t === "bitmap") return "bitmap";
  if (t === "field") return "field";
  if (t === "text") return "text";
  if (t === "sound") return "sound";
  if (t === "button") return "button";
  if (t === "colorpalette") return "colorPalette";
  if (t === "cursor") return "cursor";
  if (t === "font") return "font";
  return "empty";
}

function buildMember(row, dir) {
  const [, type, name, registrationPoint, filename] = row;
  const payload = {};
  if (type === "script" && filename) {
    const jsPath = path.join(dir, filename.replace(/\.ls$/i, ".js"));
    if (existsSync(jsPath)) payload.content = readFileSync(jsPath, "utf8");
    else if (existsSync(path.join(dir, filename))) payload.content = readFileSync(path.join(dir, filename), "utf8");
  } else if (filename && existsSync(path.join(dir, filename))) {
    const abs = path.join(dir, filename);
    if (/\.png$/i.test(filename)) {
      payload.data = "data:image/png;base64," + readFileSync(abs).toString("base64");
    } else {
      payload.text = readFileSync(abs, "utf8");
    }
  }
  return { kind: "member", name, mediaType: mediaTypeFrom(type), payload, registrationPoint };
}

function emitCast(castDir) {
  let membersCsv = path.join(castDir, "Members.csv");
  if (!existsSync(membersCsv)) {
    const alternate = readdirSync(castDir).find((f) => /_Members\.csv$/i.test(f));
    if (alternate) membersCsv = path.join(castDir, alternate);
  }
  if (!existsSync(membersCsv)) {
    throw new Error(`No Members.csv in ${castDir}`);
  }
  const rows = parseCsv(readFileSync(membersCsv, "utf8"));
  const castName = path.basename(castDir);
  const members = rows.map((r) => buildMember(r, castDir));
  const out =
    `// Generated by director generate-pack (007) — do not edit by hand.\n` +
    `// Conforms to the C8 definition contract consumed by the 008 ingester.\n` +
    `export const definition = Object.freeze({\n` +
    `  kind: "cast",\n` +
    `  name: ${JSON.stringify(castName)},\n` +
    `  members: ${JSON.stringify(members, null, 2)},\n` +
    `});\n` +
    `export default definition;\n`;
  writeFileSync(path.join(castDir, "index.js"), out);
  console.log(`wrote ${castDir}/index.js (${members.length} members)`);
}

function emitMovie(movieDir) {
  const csvPath = path.join(movieDir, "Casts.csv");
  if (!existsSync(csvPath)) {
    throw new Error(`No Casts.csv in ${movieDir}`);
  }
  const rows = parseCsv(readFileSync(csvPath, "utf8"));
  const movieName = path.basename(movieDir);
  const slotCount = rows.reduce((m, r) => Math.max(m, Number(r[0]) || 0), 0);

  const imports = [];
  const castEntries = [];
  rows.forEach(([num, name], idx) => {
    const castName = String(name).trim();
    const castDir = path.join(movieDir, "..", castName);
    const internalCsv = [path.join(movieDir, `${castName}_Members.csv`), path.join(movieDir, "Members.csv")]
      .find((p) => existsSync(p));
    if (internalCsv) {
      castEntries.push(`{ kind: "cast", name: ${JSON.stringify(castName)}, members: ${JSON.stringify(
        parseCsv(readFileSync(internalCsv, "utf8")).map((r) => buildMember(r, movieDir)),
        null,
        2
      )} }`);
    } else if (existsSync(path.join(castDir, "Members.csv"))) {
      const alias = `cast_${num}`;
      imports.push(`import { definition as ${alias} } from "../${castName}/index.js";`);
      castEntries.push(alias);
    } else {
      castEntries.push(`{ kind: "cast", name: ${JSON.stringify(castName)}, members: [] }`);
    }
  });

  const out =
    `// Generated by director generate-pack (007) — do not edit by hand.\n` +
    `// Conforms to the C8 definition contract consumed by the 008 ingester.\n` +
    imports.join("\n") + (imports.length ? "\n" : "") +
    `export const definition = Object.freeze({\n` +
    `  name: ${JSON.stringify(movieName)},\n` +
    `  totalCastSlots: ${slotCount},\n` +
    `  casts: Object.freeze([\n` +
    `    ${castEntries.join(",\n    ")}\n` +
    `  ]),\n` +
    `  options: Object.freeze({ tempo: 30, width: 640, height: 480, src: "" }),\n` +
    `});\n` +
    `export default definition;\n`;
  writeFileSync(path.join(movieDir, "index.js"), out);
  console.log(`wrote ${movieDir}/index.js (${slotCount} slots)`);
}

const [cmd, dir] = process.argv.slice(2);
if (!cmd || !dir) {
  console.error("usage: node scripts/generate-pack.mjs cast|movie <dir>");
  process.exit(1);
}
const absDir = path.resolve(dir);
try {
  if (cmd === "cast") emitCast(absDir);
  else if (cmd === "movie") emitMovie(absDir);
  else throw new Error(`unknown command ${cmd}`);
} catch (err) {
  console.error(err.message);
  process.exit(1);
}